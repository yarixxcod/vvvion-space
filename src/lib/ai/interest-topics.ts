export function topicLabel(id: string): string {
  return TOPICS.find((topic) => topic.id === id)?.label ?? "";
}

export function personalSuggestions(topicIds: string[], toneId: string): InterestCard[] {
  const picked = TOPICS.filter((topic) => topicIds.includes(topic.id));
  if (!picked.length) return [];
  const tone = TONES.find((item) => item.id === toneId) ?? TONES[0];
  if (!tone) return [];
  const out: InterestCard[] = [];
  let round = 0;
  while (out.length < 12) {
    let added = false;
    for (const topic of picked) {
      const card = topic.cards[round];
      if (!card) continue;
      out.push({ title: card.title, prompt: `${card.prompt} ${tone.line}` });
      added = true;
      if (out.length === 12) break;
    }
    if (!added) break;
    round += 1;
  }
  return out;
}
