export function updatesUnread(): boolean {
  if (typeof window === "undefined") return false;
  try {
    return localStorage.getItem(SEEN_KEY) !== RELEASE;
  } catch {
    return false;
  }
}

export function markReleaseRead(): void {
  try {
    localStorage.setItem(SEEN_KEY, RELEASE);
  } catch {
    /* private mode */
  }
  window.dispatchEvent(new Event("vvvion-release"));
}

export function useReleaseFlag(): boolean {
  const [on, setOn] = useState(false);
  useEffect(() => {
    const sync = () => setOn(updatesUnread());
    sync();
    window.addEventListener("vvvion-release", sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener("vvvion-release", sync);
      window.removeEventListener("storage", sync);
    };
  }, []);
  return on;
}